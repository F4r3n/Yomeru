use crate::reason::{Reason, Reasons};

pub struct Rule {
    pub suffix_in: &'static str,
    pub suffix_out: &'static str,
    /// What the suffix means: 食べなかった → 食べる is negative and past.
    pub reasons: Reasons,
}

macro_rules! rule {
    ($in:expr, $out:expr, $($reason:ident),+) => {
        Rule {
            suffix_in: $in,
            suffix_out: $out,
            reasons: Reasons::of(&[$(Reason::$reason),+]),
        }
    };
}

